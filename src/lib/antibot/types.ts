/**
 * Общие типы антибот-модуля.
 *
 * Архитектура «trust-gate»: один источник истины решает, доказал ли посетитель,
 * что он человек. Это состояние гейтит и инициализацию Яндекс.Метрики, и отправку
 * конверсий, и сабмит форм.
 */

/**
 * Способ прохождения поведенческого барьера.
 * - `modal`     — клик в модалке выбора региона (первичный барьер, первый визит).
 * - `returning` — валидный localStorage-флаг при повторном визите (модалка не показывается).
 * - `heuristic` — опциональный «мягкий» режим: первое живое mousemove/scroll/touchstart.
 *                 По умолчанию выключен (иначе модалка теряет смысл).
 */
export type TrustMethod = 'modal' | 'returning' | 'heuristic';

/**
 * Запись о прохождении барьера, сериализуемая в localStorage.
 */
export interface TrustRecord {
	/** Версия схемы — позволяет инвалидировать устаревший флаг при изменении логики. */
	v: 1;
	/** Unix timestamp (мс) прохождения барьера. */
	ts: number;
	/** Способ прохождения. */
	method: TrustMethod;
	/** Выбранный/подтверждённый пользователем регион. */
	region: string;
}

/**
 * Гео-информация посетителя, резолвится на сервере (см. hooks.server.ts).
 * Определяет режим модалки: confirm («Ваш регион — X?») или select («Выберите регион»).
 */
export interface GeoInfo {
	/** Название региона для отображения, например «Москва и МО». */
	region: string;
	/** Код страны (ISO 3166-1 alpha-2), если доступен. */
	country?: string;
	/** IP — это хостинг/дата-центр? (VPN/прокси/бот-фермы часто ходят отсюда). */
	isHosting?: boolean;
	/** IP помечен как прокси? */
	isProxy?: boolean;
	/** IP помечен как VPN? */
	isVpn?: boolean;
	/**
	 * Уверенность GeoIP-провайдера в результате (0..1).
	 * Низкое значение/отсутствие гео → безопасный select-режим.
	 */
	confidence: number;
}

/**
 * Опция в выпадающем списке регионов (select-режим модалки).
 */
export interface RegionOption {
	/** Идентификатор/значение региона. */
	value: string;
	/** Человекочитаемая подпись. */
	label: string;
}

/**
 * Результат верификации SmartCaptcha на стороне фронтенда.
 */
export interface CaptchaTokenResult {
	token: string | null;
	error?: string;
}

/**
 * Глобальный объект window.ym (Яндекс.Метрика).
 * Инициализируется лениво — см. metrika.ts.
 */
declare global {
	interface Window {
		ym?:
			| ((id: number, action: string, ...args: unknown[]) => void)
			| ((...args: unknown[]) => void);
	}
}

